create table if not exists public.admin_users (
  user_id uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.admin_users enable row level security;

create or replace function public.is_card_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.admin_users
    where user_id = (select auth.uid())
  );
$$;

revoke all on function public.is_card_admin() from public;
grant execute on function public.is_card_admin() to authenticated;

grant select on public.admin_users to authenticated;

drop policy if exists "Admins can read their own membership" on public.admin_users;
create policy "Admins can read their own membership"
  on public.admin_users
  for select
  to authenticated
  using (user_id = (select auth.uid()));

create table if not exists public.cards (
  id bigint generated by default as identity primary key,
  game text not null,
  name text not null,
  card_type text not null default '',
  set_name text not null default '',
  card_no text not null default '',
  rarity text not null default '',
  price numeric(10, 2) not null default 0 check (price >= 0),
  quantity integer not null default 0 check (quantity >= 0),
  description text not null default '',
  image_path text not null default '',
  is_published boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.cards enable row level security;

grant select on public.cards to anon, authenticated;
grant insert, update, delete on public.cards to authenticated;

drop policy if exists "Public can read published cards" on public.cards;
drop policy if exists "Authenticated can read published cards" on public.cards;
create policy "Public can read published cards"
  on public.cards
  for select
  to anon
  using (is_published);

create policy "Authenticated can read published cards"
  on public.cards
  for select
  to authenticated
  using (is_published or (select public.is_card_admin()));

drop policy if exists "Admins can insert cards" on public.cards;
create policy "Admins can insert cards"
  on public.cards
  for insert
  to authenticated
  with check ((select public.is_card_admin()));

drop policy if exists "Admins can update cards" on public.cards;
create policy "Admins can update cards"
  on public.cards
  for update
  to authenticated
  using ((select public.is_card_admin()))
  with check ((select public.is_card_admin()));

drop policy if exists "Admins can delete cards" on public.cards;
create policy "Admins can delete cards"
  on public.cards
  for delete
  to authenticated
  using ((select public.is_card_admin()));

